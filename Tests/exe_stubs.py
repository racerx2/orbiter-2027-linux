# not upstream: test doubles for what a module takes from Orbiter's exe: its undefined dynamic symbols that no library it loads defines.
# The release links with -z now, so all bind at load; a double that a test reaches stops it (ud2). Usage: exe_stubs.py module.so out.c
import re, subprocess, sys

def dynsyms (path):
    undef, defined = set (), set ()
    txt = subprocess.run (['readelf', '--dyn-syms', '-W', path], capture_output=True, text=True, check=True).stdout
    for line in txt.splitlines ():
        f = line.split ()
        if len (f) < 8 or not f[0].endswith (':') or not f[0][:-1].isdigit (): continue
        name = f[7].split ('@')[0]
        if not name: continue
        if f[6] == 'UND':
            if f[4] == 'GLOBAL': undef.add (name) # a weak one may stay unbound
        else: defined.add (name)
    return undef, defined

lib, out = sys.argv[1], sys.argv[2]
undef = dynsyms (lib)[0]
ldd = subprocess.run (['ldd', lib], capture_output=True, text=True).stdout
for dep in re.findall (r'(/\S+) \(0x', ldd): # the libraries it loads, the dynamic loader too (__tls_get_addr)
    undef -= dynsyms (dep)[1]
undef = {s for s in undef if not re.match (r'__(asan|ubsan|tsan|lsan|sanitizer|msan)_', s)} # the sanitizer runtime comes with the exe
with open (out, 'w') as o:
    o.write ('// generated by exe_stubs.py from %s\n' % lib)
    for s in sorted (undef):
        o.write ('__asm__ (".globl %s\\n.type %s,@function\\n%s:\\n\\tud2\\n");\n' % (s, s, s))
